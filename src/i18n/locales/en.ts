/**
 * English dictionary. Values are the exact strings the terminal rendered before
 * localization, so an English session stays byte-identical and the existing
 * snapshots remain valid; the key set is checked complete against the Chinese
 * source of truth in `zh.ts` — a missing or extra key is a compile error.
 *
 * Entries are functions where English needs a plural form Chinese does not
 * carry (`count.*`, `diff.files`, `prompt.queued`, `question.*` counts).
 * @module @shihaoshen/dsh-tui-fixed/i18n/locales/en
 */

